-- SPECIAL cloud chat storage (additive; leaves existing tables untouched)
create table if not exists public.special_cloud_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  character_id text not null,
  character_name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, character_id)
);

create table if not exists public.special_cloud_messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.special_cloud_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('user', 'model')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists special_cloud_messages_conversation_created_idx
  on public.special_cloud_messages (conversation_id, created_at desc);

create table if not exists public.special_cloud_character_memory (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  character_id text not null,
  memory_text text not null default '',
  updated_at timestamptz not null default now(),
  unique (user_id, character_id)
);

alter table public.special_cloud_conversations enable row level security;
alter table public.special_cloud_messages enable row level security;
alter table public.special_cloud_character_memory enable row level security;

-- Only the authenticated owner can read their own records.
drop policy if exists "Users read own SPECIAL cloud conversations" on public.special_cloud_conversations;
create policy "Users read own SPECIAL cloud conversations"
  on public.special_cloud_conversations for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users read own SPECIAL cloud messages" on public.special_cloud_messages;
create policy "Users read own SPECIAL cloud messages"
  on public.special_cloud_messages for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users read own SPECIAL cloud memory" on public.special_cloud_character_memory;
create policy "Users read own SPECIAL cloud memory"
  on public.special_cloud_character_memory for select to authenticated
  using (auth.uid() = user_id);

